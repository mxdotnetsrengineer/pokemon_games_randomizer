def get_gba_offset(rom_data, file_offset):
    """
    Reads 4 bytes at file_offset, interprets them as a Little Endian GBA pointer,
    and converts it into a raw PC file offset.
    Example: 45 23 1A 08 -> 0x081A2345 -> 0x1A2345 (PC Offset)
    """
    four_bytes = rom_data[file_offset : file_offset + 4]
    gba_address = int.from_bytes(four_bytes, byteorder='little')
    
    # GBA ROM pointers must reside between 0x08000000 and 0x0A000000
    if 0x08000000 <= gba_address < 0x0A000000:
        return gba_address - 0x08000000
    return None